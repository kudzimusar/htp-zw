#!/usr/bin/env node
'use strict';

import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { execSync } from 'node:child_process';
import { generateManifest, verifyManifest } from './verify-vercel-manifest.mjs';

const ROOT_DIR = process.cwd();
const OUTPUT_DIR = path.join(ROOT_DIR, '.vercel/output');
const PREVIEW_BARRIER_SOURCE = path.join(ROOT_DIR, 'api/preview-barrier.js');

// INVARIANT DEF-G3-01: Fail-Closed Package Construction
// Every required operational function bundle must be present, validly configured,
// and physically sealed with the approved preview barrier. Missing bundles, malformed
// configs, or retained operational mutation paths MUST fail closed with exit code 1.

if (!fs.existsSync(OUTPUT_DIR)) {
  console.error('[PACKAGE_FATAL] .vercel/output does not exist. Run "npm run build:phase4:web && npx vercel build --yes" first.');
  process.exit(1);
}

if (!fs.existsSync(PREVIEW_BARRIER_SOURCE)) {
  console.error('[PACKAGE_FATAL] Missing approved preview barrier source at api/preview-barrier.js');
  process.exit(1);
}

const currentSha = (function() {
  try {
    return execSync('git rev-parse HEAD', { encoding: 'utf8', cwd: ROOT_DIR }).trim();
  } catch {
    return 'local';
  }
})();

console.log(`[PACKAGE_PREVIEW] Packaging Reader-Only Preview Artifact for commit ${currentSha}`);

// 1. Ensure build-info.json in static output enforces previewLocked, reader-only profile, and source-parity
const buildInfo = {
  sha: currentSha,
  presentation: 'apps/mobile',
  capability: 'cp5-phase3-v1',
  basePath: '/',
  serviceMode: 'source-parity',
  previewLocked: true,
  profile: 'reader-only-preview'
};

const staticBuildInfoPath = path.join(OUTPUT_DIR, 'static/build-info.json');
fs.writeFileSync(staticBuildInfoPath, JSON.stringify(buildInfo, null, 2) + '\n', 'utf8');

const distBuildInfoPath = path.join(ROOT_DIR, 'apps/mobile/dist/build-info.json');
if (fs.existsSync(path.dirname(distBuildInfoPath))) {
  fs.writeFileSync(distBuildInfoPath, JSON.stringify(buildInfo, null, 2) + '\n', 'utf8');
}

// 2. Compute approved preview barrier content and hash
const barrierContent = fs.readFileSync(PREVIEW_BARRIER_SOURCE, 'utf8');
const approvedBarrierDigest = crypto.createHash('sha256').update(barrierContent).digest('hex');

// 3. Mandatory operational functions to be replaced with fail-closed barrier
const REQUIRED_MUTATING_FUNCTIONS = [
  { name: 'newsroom.func', expectedHandler: 'api/newsroom.js' },
  { name: 'communications.func', expectedHandler: 'api/communications.js' },
  { name: 'commerce.func', expectedHandler: 'api/commerce.js' }
];

const apiFunctionsDir = path.join(OUTPUT_DIR, 'functions/api');
if (!fs.existsSync(apiFunctionsDir)) {
  console.error(`[PACKAGE_FATAL] Missing serverless API directory: ${apiFunctionsDir}`);
  process.exit(1);
}

// Remove preview-barrier.func if generated by vercel build (preview-barrier is a template, not an endpoint)
const previewBarrierFunc = path.join(apiFunctionsDir, 'preview-barrier.func');
if (fs.existsSync(previewBarrierFunc)) {
  fs.rmSync(previewBarrierFunc, { recursive: true, force: true });
}

// Scan apiFunctionsDir for unexpected function bundles
const discoveredFuncs = fs.readdirSync(apiFunctionsDir).filter(name => name.endsWith('.func'));
const allowedFuncs = new Set(['public.func', ...REQUIRED_MUTATING_FUNCTIONS.map(f => f.name)]);

for (const discovered of discoveredFuncs) {
  if (!allowedFuncs.has(discovered)) {
    console.error(`[PACKAGE_FATAL] Unexpected function bundle discovered in preview artifact: ${discovered}`);
    process.exit(1);
  }
}

// Seal mutating function bundles
for (const fn of REQUIRED_MUTATING_FUNCTIONS) {
  const funcDir = path.join(apiFunctionsDir, fn.name);
  if (!fs.existsSync(funcDir)) {
    console.error(`[PACKAGE_FATAL] Required mutating function bundle missing: ${fn.name}`);
    process.exit(1);
  }

  const vcConfigPath = path.join(funcDir, '.vc-config.json');
  if (!fs.existsSync(vcConfigPath)) {
    console.error(`[PACKAGE_FATAL] Missing .vc-config.json in ${fn.name}`);
    process.exit(1);
  }

  let vcConfig;
  try {
    vcConfig = JSON.parse(fs.readFileSync(vcConfigPath, 'utf8'));
  } catch (e) {
    console.error(`[PACKAGE_FATAL] Malformed JSON in ${fn.name}/.vc-config.json: ${e.message}`);
    process.exit(1);
  }

  if (!vcConfig || typeof vcConfig !== 'object') {
    console.error(`[PACKAGE_FATAL] Invalid .vc-config.json structure in ${fn.name}`);
    process.exit(1);
  }

  // Validate handler entrypoint
  const configuredHandler = vcConfig.handler;
  if (!configuredHandler || configuredHandler !== fn.expectedHandler) {
    console.error(`[PACKAGE_FATAL] Unexpected handler entrypoint in ${fn.name}: found '${configuredHandler}', expected '${fn.expectedHandler}'`);
    process.exit(1);
  }

  // Purge all extraneous subdirectories and files in sealed bundle
  for (const entry of fs.readdirSync(funcDir, { withFileTypes: true })) {
    const fullPath = path.join(funcDir, entry.name);
    if (entry.name === '.vc-config.json') continue;
    if (entry.name === 'api') continue;
    fs.rmSync(fullPath, { recursive: true, force: true });
  }

  // Ensure clean targetScript path and replace with approved immutable preview barrier
  const targetScript = path.join(funcDir, configuredHandler);
  fs.mkdirSync(path.dirname(targetScript), { recursive: true });
  fs.writeFileSync(targetScript, barrierContent, 'utf8');

  // Verify written script hash matches approved barrier hash
  const writtenDigest = crypto.createHash('sha256').update(fs.readFileSync(targetScript)).digest('hex');
  if (writtenDigest !== approvedBarrierDigest) {
    console.error(`[PACKAGE_FATAL] Barrier integrity check failed for ${fn.name}: written digest '${writtenDigest}' does not match approved '${approvedBarrierDigest}'`);
    process.exit(1);
  }

  // Check for any retained extraneous executable files in function bundle
  function scanExtraneousJs(dir) {
    for (const ent of fs.readdirSync(dir, { withFileTypes: true })) {
      const full = path.join(dir, ent.name);
      if (ent.isDirectory()) {
        scanExtraneousJs(full);
      } else if (ent.isFile() && ent.name.endsWith('.js')) {
        const rel = path.relative(funcDir, full).replace(/\\/g, '/');
        if (rel !== configuredHandler) {
          console.warn(`[PACKAGE_CLEANUP] Removing extraneous script from ${fn.name}: ${rel}`);
          fs.unlinkSync(full);
        }
      }
    }
  }
  scanExtraneousJs(funcDir);

  // Update .vc-config.json with baked build-time preview lock environment
  vcConfig.environment = {
    ...vcConfig.environment,
    HEALTHTIMES_PREVIEW_LOCK: '1',
    HEALTHTIMES_ARTIFACT_PROFILE: 'reader-only-preview'
  };
  fs.writeFileSync(vcConfigPath, JSON.stringify(vcConfig, null, 2) + '\n', 'utf8');

  console.log(`[PACKAGE_PREVIEW] Sealed ${fn.name} with approved immutable preview barrier (entrypoint: ${configuredHandler}).`);
}

// 4. Confirm public reader function is preserved intact and properly configured
const publicFuncDir = path.join(apiFunctionsDir, 'public.func');
if (!fs.existsSync(publicFuncDir)) {
  console.error('[PACKAGE_FATAL] public.func missing from output artifact!');
  process.exit(1);
}

const publicVcConfigPath = path.join(publicFuncDir, '.vc-config.json');
if (!fs.existsSync(publicVcConfigPath)) {
  console.error('[PACKAGE_FATAL] Missing .vc-config.json in public.func!');
  process.exit(1);
}

try {
  const publicConfig = JSON.parse(fs.readFileSync(publicVcConfigPath, 'utf8'));
  if (publicConfig.handler !== 'api/public.js') {
    console.error(`[PACKAGE_FATAL] public.func handler mismatch: found '${publicConfig.handler}', expected 'api/public.js'`);
    process.exit(1);
  }
  const publicHandlerPath = path.join(publicFuncDir, publicConfig.handler);
  if (!fs.existsSync(publicHandlerPath)) {
    console.error(`[PACKAGE_FATAL] public.func entrypoint missing at ${publicHandlerPath}`);
    process.exit(1);
  }
} catch (e) {
  console.error(`[PACKAGE_FATAL] Failed to validate public.func .vc-config.json: ${e.message}`);
  process.exit(1);
}
console.log('[PACKAGE_PREVIEW] Public Reader API function verified and preserved intact.');

// 5. Generate deterministic manifest across all packaged files
const manifest = generateManifest(OUTPUT_DIR);

// 6. Run immediate read-only verification to confirm manifest matches packaged files
verifyManifest({ outputDir: OUTPUT_DIR, expectedSha: currentSha });

console.log('[PACKAGE_PREVIEW] Reader-Only Preview Artifact packaged and verified successfully.');
